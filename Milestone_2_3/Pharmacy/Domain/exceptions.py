class PharmacyError(Exception):
    """Base class for every rule violation raised by the domain layer."""

class ValidationError(PharmacyError): ...
class InvalidPriceError(ValidationError): ...
class InvalidQuantityError(ValidationError): ...
class NotFoundError(PharmacyError): ...
class DuplicateCodeError(PharmacyError): ...
class InsufficientStockError(PharmacyError): ...
class CapacityExceededError(PharmacyError): ...
class UnauthorisedPrescriberError(PharmacyError): ...
class QuantityLimitError(PharmacyError): ...
class InvalidStatusTransitionError(PharmacyError): ...
